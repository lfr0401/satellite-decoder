% 全局配置：所有参数集中在这里，改信号只动本文件
% 输出 8 个结构体，分别被链路各模块取用：
%   Data       原始 IQ 与采样率
%   Params     重采样/分块/绘图/星座映射等通用参数
%   Rcc        RRC 滤波器参数
%   Viterbi    卷积码译码参数
%   Descrambler  CCSDS 解扰序列
%   ReedSolomon RS 纠错参数
%   Huffman / DCT  JPEG 图像重建表

    % 输入文件
    filePath = "data/meteor_m2_72k.wav";   % 原始 IQ 采样（wav 双声道：左 I 右 Q）
    [Data.raw, Data.fs] = audioread(filePath);   % 读 wav：返回采样矩阵 N×2 与采样率 Hz
    Data.fileSize = size(Data.raw, 1);            % 采样点数（行数），用于末尾残块判断

    % 通用参数
    Params.blockSize = 98304;   % 分块处理的长度（符号数）= 6×16384，对齐帧结构
    Params.plotting = true;      % 是否实时绘图（各模块诊断图）
    Params.export = false;       % 是否把诊断图导出为 PDF 到 data/plots
    Params.keepPartialScans = true;  % 是否保留不完整的扫描行（图像边缘）
    if ~exist("data/plots", "dir")   % 输出目录不存在则创建，避免导出时报错
        mkdir("data/plots")
    end
    Params.minClip = -0.01;      % 限幅下门限：掐掉负向脉冲尖峰
    Params.maxClip = 0.01;       % 限幅上门限：掐掉正向脉冲尖峰
    Params.M = 4;                % 调制阶数：4 = QPSK
    Params.symbolRate = 72e3;    % 符号率 72 ksym/s（Meteor-M2 LRPT 固定值）
    Params.targetSps = 4;        % 目标每符号采样点数，定时同步插值需要 4 倍过采样
    Params.targetFs = Params.targetSps * Params.symbolRate;  % 目标采样率 = 4×72k = 288 kHz
    [Params.p, Params.q] = rat(Params.targetFs/Data.fs);     % 目标/原采样率的有理逼近 p/q，供 resample 用，采样率转换的比值
    Params.constellations = {    % 4 种星座映射，constellation.m 盲试后用同步字选正确的一种
                            [0 1 3 2], ...      % 默认
                            [1 3 2 0], ...      % 旋转 90°
                            [2 3 1 0], ...      % 虚部取反
                            [0 2 3 1], ...      % I/Q 对调
                            };

    % 升余弦滤波器（RRC）
    Rcc.rollOff = 0.35;   % 滚降系数，必须与发射端一致，否则不满足奈奎斯特、有 ISI
    Rcc.spanSym = 10;     % 冲激响应跨度（单位：符号），越长越理想但延迟越大

    % 维特比译码器（CCSDS 卷积码）
    Viterbi.codeRate = 1/2;            % 码率：每 1 输入比特出 2 编码比特
    Viterbi.constLen = 7;              % 约束长度 K=7
    Viterbi.codeGenPoly = [171 133];   % 生成多项式（八进制），与 X2604 的 (133,171) 是同一对
    Viterbi.tblen = 30;                % 回溯深度（单位：trellis 级数/信息比特数，不是约束长度）；工程上常取 5~10 倍 K，K=7 时 30 接近下限
    Viterbi.softInputWordLength = 8;   % 软判决量化位宽 8 bit，比硬判约多 2 dB 增益

    % 解扰器（255 长伪随机序列，CCSDS 加扰）
    % 加扰目的：打散长连 0/1，便于定时恢复；解扰时逐帧与本序列异或
    % 序列为 CCSDS 标准固定 255 字节，uint8 省内存
    Descrambler.pn = uint8([
        0xff 0x48 0x0e 0xc0 0x9a 0x0d 0x70 0xbc ...
